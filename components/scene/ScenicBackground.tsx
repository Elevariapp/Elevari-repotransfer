import type { CSSProperties } from 'react';
import { SCENE_LAYERS, SCENE_VIEW, type SceneLayer } from '@/lib/scene/scene-art';
import type { SceneThemeName } from '@/lib/scene/scene-data';
import SceneController from './SceneController';
import './scene-themes.css';
import './scene.css';

export interface ScenicBackgroundProps {
  /** `full` is the whole picture (hero, login, registration); `lite` is the sky and ridges only, for strips and bands. */
  variant?: 'full' | 'lite';
  /** `auto` follows <html data-elevari-scene>: the visitor's choice, the site theme or the local time of day. */
  theme?: 'auto' | SceneThemeName;
  /** Darkening that keeps the text placed on top of the scene legible. */
  scrim?: 'hero' | 'auth' | 'center' | 'none';
  /** Unique per scene on a page; the SVG gradient ids derive from it. */
  idPrefix: string;
  className?: string;
  /** Which part of the picture stays in view when the box is wider than the picture: 0 = the sky, 1 = the camp. */
  focus?: number;
  /** Hover and tap reactions (the fire flares, the sun and the moon answer). Only the home hero asks for them. */
  interactive?: boolean;
}

type Vars = CSSProperties & { [name: `--${string}`]: string | number };

const VIEW = `0 0 ${SCENE_VIEW.w} ${SCENE_VIEW.h}`;

function layerStyle({ du, dl, vars }: SceneLayer): Vars | undefined {
  if (du === undefined && dl === undefined && !vars) return undefined;
  const style: Vars = {};
  if (du !== undefined) style['--du'] = `${du}s`;
  if (dl !== undefined) style['--dl'] = `${dl}s`;
  if (vars) for (const [name, value] of Object.entries(vars)) style[`--${name}`] = `${value}px`;
  return style;
}

/**
 * The Elevari landscape: a stack of server-rendered SVG layers (generated by scripts/scene, never edited by hand) in
 * a box that fills its positioned parent. The colours and the light are CSS variables, so one markup serves the day,
 * golden-hour and night pictures and cross-fades between them.
 */
export default function ScenicBackground({
  variant = 'full',
  theme = 'auto',
  scrim = 'none',
  idPrefix,
  className = '',
  focus,
  interactive = false,
}: ScenicBackgroundProps) {
  const layers = variant === 'lite' ? SCENE_LAYERS.filter((layer) => layer.lite) : SCENE_LAYERS;
  const style: Vars | undefined = focus === undefined ? undefined : { '--sc-fy': focus };

  return (
    <div
      className={`sc ${className}`.trim()}
      data-scene={theme}
      data-variant={variant}
      data-scrim={scrim}
      style={style}
      aria-hidden="true"
    >
      {layers.map((layer) => (
        <div key={layer.id} className="sc-l" data-l={layer.id} data-d={layer.depth}>
          <svg
            className={`sc-s${layer.anim ? ` a-${layer.anim}` : ''}`}
            viewBox={VIEW}
            focusable="false"
            style={layerStyle(layer)}
            dangerouslySetInnerHTML={{ __html: layer.svg.split('@@').join(`${idPrefix}-`) }}
          />
        </div>
      ))}
      {scrim !== 'none' && <div className="sc-scrim" />}
      <SceneController interactive={interactive} />
    </div>
  );
}
