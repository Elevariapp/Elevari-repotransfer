#!/usr/bin/env node
/**
 * Generates the Elevari scene (the vector sunset/moonlit lake used behind login, registration, hero
 * bands, the mobile app and the email banner) from scripts/scene/art.mjs + themes.mjs.
 *
 *   node scripts/scene/generate-scene.mjs           write every output
 *   node scripts/scene/generate-scene.mjs --check   fail if a committed output is stale (needs no sharp)
 *
 * Outputs
 *   lib/scene/scene-data.ts               geometry + colour tables for the web renderer
 *   mobile/lib/scene-data.ts              identical copy for the React Native renderer
 *   components/scene/scene-themes.css     per-theme CSS variables (typed with @property so they cross-fade)
 *   public/brand/email/banner.jpg         flat 1200x400 banner for transactional email (not byte-checked)
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildScene } from './art.mjs';
import { composeSvg } from './compose.mjs';
import { assertThemes, SCENE_HOURS, SKY_STOPS, THEMES, THEME_NAMES } from './themes.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const CHECK = process.argv.includes('--check');
const HEADER = '@generated by scripts/scene/generate-scene.mjs (npm run scene:generate). Do not edit by hand.';

const kebab = (key) => key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`).replace(/(\d+)/, '-$1');
const isColor = (v) => typeof v === 'string';
const rows = (list) => `[\n${list.map((r) => `  ${JSON.stringify(r)},`).join('\n')}\n]`;

function renderTs(scene) {
  const tokenKeys = Object.keys(THEMES.golden);
  const tokenType = tokenKeys.map((k) => `  ${k}: ${isColor(THEMES.golden[k]) ? 'string' : 'number'};`).join('\n');
  const themes = THEME_NAMES.map((name) => {
    const body = tokenKeys.map((k) => `    ${k}: ${isColor(THEMES[name][k]) ? `'${THEMES[name][k]}'` : THEMES[name][k]},`).join('\n');
    return `  ${name}: {\n${body}\n  },`;
  }).join('\n');
  const ridge = (r) => `{ d: '${r.d}', crest: '${r.crest}', top: ${r.top} }`;
  const cluster = (c) => `{
    back: '${c.back}',
    front: '${c.front}',
    bank: '${c.bank}',
    cabin: ${c.cabin ? JSON.stringify(c.cabin).replace(/"/g, "'").replace(/'(\w+)':/g, '$1:') : 'null'},
  }`;
  return `/* eslint-disable */
// ${HEADER}

export type SceneThemeName = ${THEME_NAMES.map((n) => `'${n}'`).join(' | ')};

/** Local-clock boundaries (24 h). Golden hour covers dawn and dusk, night wraps around midnight. */
export const SCENE_HOURS = { dawn: ${SCENE_HOURS.dawn}, day: ${SCENE_HOURS.day}, dusk: ${SCENE_HOURS.dusk}, night: ${SCENE_HOURS.night} } as const;

/** The time-of-day theme for a local hour (0-23). */
export function sceneForHour(hour: number): SceneThemeName {
  if (hour >= SCENE_HOURS.night || hour < SCENE_HOURS.dawn) return 'night';
  if (hour >= SCENE_HOURS.day && hour < SCENE_HOURS.dusk) return 'day';
  return 'golden';
}

export interface SceneTokens {
${tokenType}
}

export interface SceneRidge {
  readonly d: string;
  readonly crest: string;
  readonly top: number;
}

export interface ScenePineCluster {
  readonly back: string;
  readonly front: string;
  readonly bank: string;
  readonly cabin: {
    readonly body: string;
    readonly win: readonly [number, number, number, number];
    readonly glow: readonly [number, number, number];
  } | null;
}

/** [x, y, radius, twinkle group 0-2, opacity] */
export type SceneStar = readonly [number, number, number, number, number];
/** [x, y, width, height] */
export type SceneGlint = readonly [number, number, number, number];
/** [x, y, width, opacity] */
export type SceneRipple = readonly [number, number, number, number];

export const SCENE_VIEW = { w: ${scene.view.w}, h: ${scene.view.h} } as const;
export const SCENE_PINES_VIEW = { w: ${scene.pinesView.w}, h: ${scene.pinesView.h} } as const;
export const SCENE_SUN = { x: ${scene.sun.x}, y: ${scene.sun.y}, r: ${scene.sun.r} } as const;
export const SCENE_MOON = { x: ${scene.moon.x}, y: ${scene.moon.y}, r: ${scene.moon.r} } as const;
export const SCENE_SHORE = ${scene.shore};
export const SCENE_SKY_STOPS: readonly number[] = ${JSON.stringify(SKY_STOPS)};

export const SCENE_RIDGES: { readonly far: SceneRidge; readonly mid: SceneRidge; readonly near: SceneRidge } = {
  far: ${ridge(scene.ridges.far)},
  mid: ${ridge(scene.ridges.mid)},
  near: ${ridge(scene.ridges.near)},
};

export const SCENE_LAKE: {
  readonly d: string;
  readonly reflection: string;
  readonly glints: readonly SceneGlint[];
  readonly ripples: readonly SceneRipple[];
} = {
  d: '${scene.lake.d}',
  reflection: '${scene.lake.reflection}',
  glints: ${rows(scene.lake.glints)},
  ripples: ${rows(scene.lake.ripples)},
};

export const SCENE_MIST: readonly { readonly cx: number; readonly cy: number; readonly rx: number; readonly ry: number }[] = ${JSON.stringify(scene.mist)};

export const SCENE_PINES: { readonly left: ScenePineCluster; readonly right: ScenePineCluster } = {
  left: ${cluster(scene.pines.left)},
  right: ${cluster(scene.pines.right)},
};

export const SCENE_STARS: readonly SceneStar[] = ${rows(scene.stars)};

/** layer 0 = high streaks, 1 = low streaks near the horizon */
export const SCENE_CLOUDS: readonly { readonly layer: 0 | 1; readonly o: number; readonly d: string }[] = ${rows(scene.clouds)};

export const SCENE_RAYS: readonly { readonly d: string; readonly o: number }[] = ${rows(scene.rays)};

export const SCENE_THEMES: Record<SceneThemeName, SceneTokens> = {
${themes}
};
`;
}

function renderCss() {
  const keys = Object.keys(THEMES.golden);
  const vars = (name) => keys.map((k) => `  --sc-${kebab(k)}: ${THEMES[name][k]};`).join('\n');
  const props = keys
    .map(
      (k) => `@property --sc-${kebab(k)} {
  syntax: '${isColor(THEMES.golden[k]) ? '<color>' : '<number>'}';
  inherits: true;
  initial-value: ${THEMES.golden[k]};
}`,
    )
    .join('\n');
  const transition = keys.map((k) => `--sc-${kebab(k)}`).join(',\n    ');
  const skyStops = SKY_STOPS.map((s, i) => `var(--sc-sky-${i}) ${Math.round(s * 1000) / 10}%`).join(', ');
  return `/* ${HEADER} */
${props}

/* golden is the default, also when JS is off */
.sc[data-scene='golden'],
.sc[data-scene='auto'] {
${vars('golden')}
}

.sc[data-scene='day'],
html[data-elevari-scene='day'] .sc[data-scene='auto'] {
${vars('day')}
}

.sc[data-scene='night'],
html[data-elevari-scene='night'] .sc[data-scene='auto'] {
${vars('night')}
}

/* The registered variables interpolate, so a change of time of day cross-fades every gradient and fill */
.sc {
  transition-property:
    ${transition};
  transition-duration: 1.8s;
  transition-timing-function: ease;
}

@media (prefers-reduced-motion: reduce) {
  .sc {
    transition: none;
  }
}

/* The sky is a CSS gradient (not an SVG one) so every browser repaints it while the variables interpolate. Its stops
   come from SKY_STOPS, which keeps the horizon colour aligned with the ridges. */
.sc-sky {
  background: linear-gradient(to bottom, ${skyStops}, var(--sc-sky-${SKY_STOPS.length - 1}));
}
`;
}

async function renderBanner(scene) {
  const { default: sharp } = await import('sharp');
  // 3:1 crop of the scene (sky + sun + ridges + a sliver of lake). The scrim darkens the left and centre, where the
  // left-aligned brand lockup sits (white 30px wordmark, 13px cream tagline), and leaves the sun side bright.
  const y = 300;
  const scrim = `<defs>
<linearGradient id="bannerScrim" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#1c0803" stop-opacity=".66"/><stop offset=".5" stop-color="#1c0803" stop-opacity=".56"/><stop offset="1" stop-color="#1c0803" stop-opacity="0"/></linearGradient>
</defs>
<rect x="0" y="${y}" width="1600" height="533" fill="url(#bannerScrim)"/>`;
  const svg = composeSvg(scene, 'golden', { crop: [0, y, 1600, 533], width: 1200, height: 400, sunX: 1230, scrim });
  // Baseline JPEG: the widest email-client support (progressive scans render poorly in some Outlook builds).
  return sharp(Buffer.from(svg)).jpeg({ quality: 82, mozjpeg: true }).toBuffer();
}

async function main() {
  assertThemes();
  const scene = buildScene();
  const ts = renderTs(scene);
  const outputs = {
    'lib/scene/scene-data.ts': ts,
    'mobile/lib/scene-data.ts': ts,
    'components/scene/scene-themes.css': renderCss(),
  };

  if (CHECK) {
    const stale = [];
    for (const [file, content] of Object.entries(outputs)) {
      const current = await readFile(join(ROOT, file), 'utf8').catch(() => null);
      if (current !== content) stale.push(file);
    }
    if (stale.length) {
      console.error(`Scene outputs are stale: ${stale.join(', ')}\nRun: npm run scene:generate`);
      process.exit(1);
    }
    console.log('Scene outputs are up to date.');
    return;
  }

  for (const [file, content] of Object.entries(outputs)) {
    await mkdir(dirname(join(ROOT, file)), { recursive: true });
    await writeFile(join(ROOT, file), content);
    console.log(`wrote ${file} (${(content.length / 1024).toFixed(1)} KB)`);
  }
  const banner = await renderBanner(scene);
  const bannerPath = join(ROOT, 'public/brand/email/banner.jpg');
  await mkdir(dirname(bannerPath), { recursive: true });
  await writeFile(bannerPath, banner);
  console.log(`wrote ${relative(ROOT, bannerPath)} (${(banner.length / 1024).toFixed(1)} KB)`);
}

await main();
