#!/usr/bin/env node
/**
 * Generates the Elevari scene (the vector glamping valley that sits behind the home hero, the auth pages and the
 * catalog hero) from scripts/scene/*.mjs. One source of truth: the layers, the three times of day and their colours.
 *
 *   node scripts/scene/generate-scene.mjs           write every output
 *   node scripts/scene/generate-scene.mjs --check   fail if a committed output is stale (needs no sharp)
 *
 * Outputs
 *   lib/scene/scene-art.ts                the SVG of every layer (CSS variables for colour, so a theme change cross-fades)
 *   lib/scene/scene-data.ts               theme names, Spanish labels, local-clock boundaries
 *   components/scene/scene-themes.css     typed (@property) per-theme variables and their transitions
 *
 * Previews and the flat renderer used for email banners live next to this file (preview.mjs, compose.mjs).
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildScene } from './scene.mjs';
import { cssVar, makeRenderer } from './svg.mjs';
import { assertThemes, SCENE_HOURS, SCENE_LABELS, SCENE_ORDER, THEMES, THEME_NAMES } from './themes.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const CHECK = process.argv.includes('--check');
const HEADER = '@generated by scripts/scene/generate-scene.mjs (npm run scene:generate). Do not edit by hand.';

const isColor = (v) => typeof v === 'string';
const union = (names) => names.map((n) => `'${n}'`).join(' | ');

function literal(svg) {
  if (/[`\\]|\$\{/.test(svg)) throw new Error('scene markup contains a character that cannot live in a template literal');
  return `\`${svg}\``;
}

function renderArt(scene) {
  const r = makeRenderer('css');
  const rows = scene.units.map((u) => {
    const f = [`id: '${u.ids[0]}'`, `depth: ${u.depth}`];
    if (u.lite) f.push('lite: true');
    if (u.a) {
      f.push(`anim: '${u.a}'`);
      if (u.du) f.push(`du: ${u.du}`);
      if (u.dl) f.push(`dl: ${u.dl}`);
      if (u.v) f.push(`vars: ${JSON.stringify(u.v).replace(/"(\w+)":/g, '$1: ').replace(/,/g, ', ')}`);
    }
    f.push(`svg: ${literal(r.layer(u))}`);
    return `  { ${f.join(', ')} },`;
  });
  return `/* eslint-disable */
// ${HEADER}

/** One slice of the picture, back to front. \`depth\` is the parallax factor (0 = sky, 5 = foreground). */
export interface SceneLayer {
  readonly id: string;
  readonly depth: number;
  /** Part of the lite variant (horizon strips). */
  readonly lite?: true;
  /** Layer-wide animation: the SVG gets the class \`a-<anim>\`, with --du / --dl in seconds and vars in px. */
  readonly anim?: string;
  readonly du?: number;
  readonly dl?: number;
  readonly vars?: Readonly<Record<string, number>>;
  /** Inner SVG. Gradient and clip ids start with "@@", which the renderer replaces with the instance prefix. */
  readonly svg: string;
}

export const SCENE_VIEW = { w: ${scene.view.w}, h: ${scene.view.h} } as const;

export const SCENE_LAYERS: readonly SceneLayer[] = [
${rows.join('\n')}
];
`;
}

function renderData() {
  const labels = SCENE_ORDER.map((n) => `  ${n}: '${SCENE_LABELS[n]}',`).join('\n');
  return `/* eslint-disable */
// ${HEADER}

export type SceneThemeName = ${union(THEME_NAMES)};

/** The scenes in the order of the Día · Tarde · Noche switcher. "golden" is the afternoon scene. */
export const SCENE_ORDER: readonly SceneThemeName[] = [${SCENE_ORDER.map((n) => `'${n}'`).join(', ')}];

export const SCENE_LABELS: Record<SceneThemeName, string> = {
${labels}
};

/** Local-clock boundaries (24 h). Golden hour covers dawn and dusk, night wraps around midnight. */
export const SCENE_HOURS = { dawn: ${SCENE_HOURS.dawn}, day: ${SCENE_HOURS.day}, dusk: ${SCENE_HOURS.dusk}, night: ${SCENE_HOURS.night} } as const;

/** The time-of-day theme for a local hour (0-23). */
export function sceneForHour(hour: number): SceneThemeName {
  if (hour >= SCENE_HOURS.night || hour < SCENE_HOURS.dawn) return 'night';
  if (hour >= SCENE_HOURS.day && hour < SCENE_HOURS.dusk) return 'day';
  return 'golden';
}
`;
}

function renderCss() {
  const keys = Object.keys(THEMES.golden);
  const vars = (name) => keys.map((k) => `  ${cssVar(k)}: ${THEMES[name][k]};`).join('\n');
  const props = keys
    .map(
      (k) => `@property ${cssVar(k)} {
  syntax: '${isColor(THEMES.golden[k]) ? '<color>' : '<number>'}';
  inherits: true;
  initial-value: ${THEMES.golden[k]};
}`,
    )
    .join('\n');
  const transition = keys.map((k) => cssVar(k)).join(',\n    ');
  return `/* ${HEADER} */
${props}

/* golden is the default, also when JS is off */
.sc[data-scene='golden'],
.sc[data-scene='auto'] {
${vars('golden')}
}

.sc[data-scene='day'],
html[data-elevari-scene='day'] .sc[data-scene='auto'] {
${vars('day')}
}

.sc[data-scene='night'],
html[data-elevari-scene='night'] .sc[data-scene='auto'] {
${vars('night')}
}

/* The registered variables interpolate, so a change of time of day cross-fades every gradient, fill and light */
.sc {
  transition-property:
    ${transition};
  transition-duration: 1.8s;
  transition-timing-function: ease;
}

@media (prefers-reduced-motion: reduce) {
  .sc {
    transition: none;
  }
}
`;
}

async function main() {
  assertThemes();
  const scene = buildScene();
  const outputs = {
    'lib/scene/scene-art.ts': renderArt(scene),
    'lib/scene/scene-data.ts': renderData(),
    'components/scene/scene-themes.css': renderCss(),
  };

  if (CHECK) {
    const stale = [];
    for (const [file, content] of Object.entries(outputs)) {
      const current = await readFile(join(ROOT, file), 'utf8').catch(() => null);
      if (current !== content) stale.push(file);
    }
    if (stale.length) {
      console.error(`Scene outputs are stale: ${stale.join(', ')}\nRun: npm run scene:generate`);
      process.exit(1);
    }
    console.log('Scene outputs are up to date.');
    return;
  }

  for (const [file, content] of Object.entries(outputs)) {
    await mkdir(dirname(join(ROOT, file)), { recursive: true });
    await writeFile(join(ROOT, file), content);
    console.log(`wrote ${file} (${(content.length / 1024).toFixed(1)} KB)`);
  }
}

await main();
