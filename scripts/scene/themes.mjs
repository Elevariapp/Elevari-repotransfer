const channel = (h, i) => parseInt(h.slice(1 + i * 2, 3 + i * 2), 16);
const toHex = (r, g, b) =>
  `#${[r, g, b].map((v) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')).join('')}`;

export function mix(a, b, t) {
  return toHex(
    channel(a, 0) + (channel(b, 0) - channel(a, 0)) * t,
    channel(a, 1) + (channel(b, 1) - channel(a, 1)) * t,
    channel(a, 2) + (channel(b, 2) - channel(a, 2)) * t,
  );
}

export const darken = (a, t) => mix(a, '#000000', t);

