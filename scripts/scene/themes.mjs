/**
 * Colour and light tables for the three times of day, drawn from the Elevari palette
 * (terracotta #C2410C, deep #9A340E, umber #431407, amber #F59E0B, cream #FEF3C7).
 *
 * Hex values are colours, every other value is a number (an opacity, a position or a scale). Each theme defines
 * exactly the same keys and the generator enforces it. Every key becomes a CSS variable on the web (`--sc-<kebab>`,
 * typed with @property so a theme change cross-fades) and a plain lookup in React Native and in the flat composer.
 *
 * Objects that sit in the scene (people, domes, decks, tables) are authored once in their natural colours and graded
 * per theme with AMBIENT, so the family keeps the same clothes from sunrise to moonlight and only the light changes.
 */
export const THEME_NAMES = ['golden', 'day', 'night'];

